import type { OutboundPayload } from '../agents/loop/payload.js';
import { redactText } from '../core/logger.js';
import { escapeCardText } from '../discord/embeds/approval.js';
import { buildMessage } from '../discord/embeds/index.js';
import type { Item, Ref } from '../discord/commands/plans.js';

/** Discord's own limits for one embed; a card that would exceed them is refused, never cut (Gate 1 C8). */
const FIELD_NAME_MAX = 256;
const FIELD_VALUE_MAX = 1024;
const FIELDS_MAX = 24; // one is left for Praw's note
const TOTAL_MAX = 5000;
export const NOTE_MAX = 300;
const SNOWFLAKE = /^\d{17,20}$/;

export interface CardItem extends Item {
  /** ⚠ on this line. */
  risk?: boolean;
  /** Gate 1 S18-S20, S29: a code-written warning shown under the change (a target Praw chose, a weakened rule). */
  warn?: string;
  /** SK7: a one-value field (label = name, `plain` = value, escaped with no cut). `old` and `neu` are not shown. Model text rides here, labelled by the caller, never merged with a code-written field. */
  plain?: string;
}

export interface CardInput {
  id: string;
  proposerId: string;
  title: string;
  items: CardItem[];
  /** The history or a tool result in view was untrusted (C8): the card says so. */
  tainted: boolean;
  /** Praw's own words, shown apart and labelled as not part of the change. */
  note?: string | undefined;
}

export type Rendered = { payload: OutboundPayload } | { error: string };
const TOO_LARGE = 'The proposal is too large to show on one card in full; split it into smaller proposals.';

/** A role, channel or member as a mention plus its raw id, from an id that is a real snowflake (never a model-supplied name). */
export function mentionOf(r: Ref): string | null {
  if (!SNOWFLAKE.test(r.id)) return null;
  const m = r.kind === 'channel' ? `<#${r.id}>` : r.kind === 'role' ? `<@&${r.id}>` : `<@${r.id}>`;
  return `${m} (\`${r.id}\`)`;
}

/**
 * Gate 1 C8: the card is generated by code from the stored structured ops. Every value goes through escapeCardText with no cut
 * (a value that does not fit refuses the proposal); ids are shown as mention + raw id; the model's note is a separate labelled field.
 */
export function renderCard(c: CardInput, secrets: readonly string[] = []): Rendered {
  if (!SNOWFLAKE.test(c.proposerId)) return { error: 'Cannot render the card: the proposer is not a Discord user id.' };
  if (c.items.length === 0 || c.items.length > FIELDS_MAX) return { error: TOO_LARGE };
  // G2A-05: a value the masker would change cannot be shown as it is, so it cannot be confirmed: refuse it rather than apply it unseen.
  let secretLike = false;
  const esc = (s: string) => {
    if (redactText(s, secrets) !== s) secretLike = true;
    return escapeCardText(s, 1_000_000, secrets); // the real limit is checked on the escaped text below
  };
  const fields: { name: string; value: string }[] = [];
  for (const it of c.items) {
    if (it.plain !== undefined) {
      const name = esc(it.label);
      const value = esc(it.plain);
      if (name.length > FIELD_NAME_MAX || value.length > FIELD_VALUE_MAX || !value.length) return { error: TOO_LARGE };
      fields.push({ name, value });
      continue;
    }
    const refs: string[] = [];
    for (const r of it.refs ?? []) {
      const m = mentionOf(r);
      if (!m) return { error: 'Cannot render the card: an id in the proposal is not a Discord id.' };
      refs.push(m);
    }
    const name = `${it.risk ? '⚠ ' : ''}${esc(it.label)}`;
    const change = `${esc(it.old)} → ${esc(it.neu)}`;
    const value = [...(refs.length ? [refs.join(' ')] : []), change].join('\n');
    if (name.length > FIELD_NAME_MAX || value.length > FIELD_VALUE_MAX) return { error: TOO_LARGE };
    fields.push({ name, value });
    if (it.warn !== undefined) {
      const warn = esc(it.warn);
      if (warn.length > FIELD_VALUE_MAX) return { error: TOO_LARGE };
      fields.push({ name: '⚠ Warning', value: warn });
    }
    if (it.detail !== undefined) {
      const detail = esc(it.detail);
      if (detail.length > FIELD_VALUE_MAX) return { error: TOO_LARGE };
      fields.push({ name: 'Full text', value: detail });
    }
  }
  if (c.note) {
    const note = esc(c.note);
    if (note.length > NOTE_MAX * 2) return { error: TOO_LARGE };
    fields.push({ name: "Praw's note (not part of the change)", value: note });
  }
  if (fields.length > 25 || fields.reduce((n, f) => n + f.name.length + f.value.length, 0) > TOTAL_MAX) return { error: TOO_LARGE };
  if (secretLike) return { error: 'A value in the proposal looks like a secret (a token or key) and cannot be set from Discord.' };
  const risky = c.items.some((i) => i.risk);
  const body = [
    `Proposed by <@${c.proposerId}>. **Confirm** applies exactly the items below; nothing changes before that. Valid for 15 minutes, once.`,
    ...(risky ? ['⚠ marks an item that raises spend or reach.'] : []),
    ...(c.tainted ? ['History contained untrusted content (other people\'s messages, files or tool output). Read every item as if a stranger wrote it.'] : []),
  ].join('\n');
  const payload: OutboundPayload = { type: 'approval', origin: 'governance', title: `${c.title} #${c.id.slice(0, 8)}`, body, fields, adminCardId: c.id };
  // The buttons sit on the last message and port.post returns the first id: a card must be exactly one message (C5 step 5).
  if (buildMessage(payload, { deptColor: 0 }).length !== 1) return { error: TOO_LARGE };
  return { payload };
}
