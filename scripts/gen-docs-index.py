#!/usr/bin/env python3
"""Regenerate docs/**/_index.md as full tables of contents (every doc + its H2/H3 headings, linked by anchor).

Usage: scripts/gen-docs-index.py [--check]
Descriptions are kept from the existing index lines ("- [title](file) — desc"); a doc without one gets its first
paragraph line. --check exits 1 if any index is out of date (for CI / pre-commit).
"""
import re
import sys
from pathlib import Path

DOCS = Path(__file__).resolve().parent.parent / "docs"
LINE = re.compile(r"^- \[[^\]]*\]\(([^)]+\.md)\) — (.+)$")
HEAD = re.compile(r"^(#{1,3})\s+(.+?)\s*#*\s*$")


def anchor(text: str, seen: dict[str, int]) -> str:
    """GitHub-style slug: lower case, drop punctuation/emoji, spaces to '-', duplicates get -1, -2."""
    text = re.sub(r"`|\*\*|__|\[([^\]]*)\]\([^)]*\)", r"\1", text)
    slug = re.sub(r"[^\w\- ]", "", text.lower()).replace(" ", "-")
    n = seen.get(slug, 0)
    seen[slug] = n + 1
    return f"{slug}-{n}" if n else slug


def parse(path: Path) -> tuple[str, list[tuple[int, str, str]], str]:
    """(title, [(level, heading, anchor)], first paragraph line). Skips fenced code blocks."""
    title, heads, para, fence, seen = path.stem, [], "", False, {}
    lines = path.read_text(encoding="utf-8").splitlines()
    if lines and lines[0] == "---" and "---" in lines[1:]:   # YAML frontmatter: take its title, skip the block
        end = lines.index("---", 1)
        for ln in lines[1:end]:
            if ln.startswith("title:"):
                title = ln[6:].strip().strip("\"'")
        lines = lines[end + 1:]
    for ln in lines:
        if ln.lstrip().startswith(("```", "~~~")):
            fence = not fence
            continue
        if fence:
            continue
        m = HEAD.match(ln)
        if m:
            level, text = len(m.group(1)), m.group(2)
            a = anchor(text, seen)
            if level == 1 and title == path.stem:
                title = text
            elif level > 1 and text.lower() not in ("contents", "table of contents"):
                heads.append((level, text, a))
        elif not para and ln.strip() and not ln.startswith(("|", ">", "-", "<", "!")):
            para = ln.strip()[:140]
    return title, heads, para


def old_descriptions(index: Path) -> dict[str, str]:
    if not index.exists():
        return {}
    return {m.group(1): m.group(2) for m in map(LINE.match, index.read_text(encoding="utf-8").splitlines()) if m}


def toc(folder: Path, prefix: str, descs: dict[str, str]) -> list[str]:
    """TOC lines for the docs directly in folder; links are relative to the index that will hold them."""
    out = []
    for doc in sorted(p for p in folder.glob("*.md") if p.name != "_index.md"):
        title, heads, para = parse(doc)
        desc = descs.get(doc.name) or para
        out.append(f"- [{title}]({prefix}{doc.name})" + (f" — {desc}" if desc else ""))
        for level, text, a in heads:
            out.append(f"{'  ' * (level - 1)}- [{text}]({prefix}{doc.name}#{a})")
    return out


CONTENTS_LINE = re.compile(r"^(\s*- )(.+?) — L(\d+)(\s*)$")


def fix_contents(path: Path) -> bool:
    """Repoint "- Heading — L<n>" Contents entries at the line of the heading with that text. True if changed."""
    lines, fence, at = path.read_text(encoding="utf-8").splitlines(), False, {}
    for i, ln in enumerate(lines, 1):
        if ln.lstrip().startswith(("```", "~~~")):
            fence = not fence
        elif not fence and (m := HEAD.match(ln)):
            at.setdefault(m.group(2), i)
    out = []
    for ln in lines:
        m = CONTENTS_LINE.match(ln)
        n = at.get(m.group(2)) if m else None
        out.append(f"{m.group(1)}{m.group(2)} — L{n}{m.group(4)}" if n else ln)
    if out != lines:
        path.write_text("\n".join(out) + "\n", encoding="utf-8")
        return True
    return False


def folders() -> list[Path]:
    return sorted({p.parent for p in DOCS.rglob("*.md")} - {DOCS})


def build() -> dict[Path, str]:
    files, root = {}, ["# Docs — full table of contents", "",
                       "Generated by `scripts/gen-docs-index.py`. Do not edit by hand; rerun the script after changing docs.",
                       "Every doc is listed with its sections. Click a section to jump straight to it.", "", "## Contents", ""]
    for f in folders():
        rel = f.relative_to(DOCS).as_posix()
        root.append(f"- [{rel}](#{anchor(rel, {})})")
    root.append("")
    for f in folders():
        rel = f.relative_to(DOCS).as_posix()
        index = f / "_index.md"
        descs = old_descriptions(index)
        local = toc(f, "", descs)
        files[index] = "\n".join([f"# {rel} — index", "", f"Up: [docs index]({'../' * (rel.count('/') + 1)}_index.md)", ""]
                                 + local) + "\n"
        root += [f"## {rel}", "", f"Folder index: [{rel}/_index.md]({rel}/_index.md)", ""] + toc(f, f"{rel}/", descs) + [""]
    files[DOCS / "_index.md"] = "\n".join(root).rstrip() + "\n"
    return files


def main() -> int:
    stale = []
    for doc in sorted(p for p in DOCS.rglob("*.md") if p.name != "_index.md"):
        if "--check" not in sys.argv and fix_contents(doc):
            print("contents: " + str(doc.relative_to(DOCS.parent)))
    for path, text in build().items():
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            stale.append(path)
            if "--check" not in sys.argv:
                path.write_text(text, encoding="utf-8")
    for p in stale:
        print(("stale: " if "--check" in sys.argv else "wrote: ") + str(p.relative_to(DOCS.parent)))
    return 1 if stale and "--check" in sys.argv else 0


if __name__ == "__main__":
    assert anchor("§12.14 System log bot (Praw)", {}) == "1214-system-log-bot-praw"
    assert anchor("✅ Approvals", {}) == "-approvals"
    sys.exit(main())
