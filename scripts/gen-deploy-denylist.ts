/**
 * Refreshes the GitHub write hard denylist (Gate P6b, PF19) from the lw-git deploy sources:
 *   node scripts/gen-deploy-denylist.ts            (reads LW_INFRA_DIR, default ../infra)
 * It writes tests/fixtures/lw-git-repos.txt (the snapshot the unit test uses when LW_INFRA_DIR is unset) and
 * tools/plugins/github/deploy-repos.json (what deny.ts loads). Run it after `lw add` or any app.conf change and commit both.
 * No relative imports: it runs under plain Node type stripping.
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const SNAPSHOT_PATH = join(ROOT, 'tests', 'fixtures', 'lw-git-repos.txt');
export const DENYLIST_PATH = join(ROOT, 'tools', 'plugins', 'github', 'deploy-repos.json');
const APPS = join('vps', 'files', 'lw-git', 'apps');

/** Always denied besides the app.conf sources (P6b): the infra repo, this bot and the old bot. */
export const EXTRA_FULL_NAMES = ['Lab-Work-Space/labworkspace-infra', 'Lab-Work-Space/Assistant', 'Lab-Work-Space/Discord_bot'];
/** Denied under any owner (a fork or transfer keeps the name). */
export const BARE_NAMES = ['Assistant', 'Discord_bot'];

/** `REPO=` value (ssh, ssh://, https; optional quotes and `.git`) -> `Owner/Name`. */
export function parseRepoLine(value: string): string {
  const v = value.trim().replace(/^(['"])(.*)\1$/, '$2').trim();
  const m = /^(?:git@github\.com:|ssh:\/\/git@github\.com\/|https:\/\/github\.com\/)([A-Za-z0-9_.-]+)\/([A-Za-z0-9_.-]+?)(?:\.git)?\/?$/.exec(v);
  if (!m) throw new Error('unrecognised REPO= value in an app.conf (expected a github.com ssh or https url)');
  return `${m[1]}/${m[2]}`;
}

/** Every `REPO=` of `<infraDir>/vps/files/lw-git/apps/<app>/app.conf`, sorted by app. A missing directory is an error, never an empty list. */
export function readAppConfRepos(infraDir: string): string[] {
  const apps = join(infraDir, APPS);
  if (!existsSync(apps)) throw new Error(`LW_INFRA_DIR=${infraDir}: ${APPS.split('\\').join('/')} not found (set LW_INFRA_DIR to the labworkspace-infra checkout)`);
  const out: string[] = [];
  for (const app of readdirSync(apps).sort()) {
    const conf = join(apps, app, 'app.conf');
    if (!existsSync(conf)) continue;
    for (const raw of readFileSync(conf, 'utf8').split('\n')) {
      const line = raw.trim();
      if (!line.startsWith('REPO=')) continue; // comments (#REPO=) and other keys are skipped
      out.push(parseRepoLine(line.slice('REPO='.length).replace(/\s+#.*$/, '')));
    }
  }
  return out;
}

export type Denylist = { comment: string; fullNames: string[]; names: string[]; ids: number[] };

/** The JSON deny.ts loads. `ids` is for known repository ids (the app.conf files carry none); it starts empty. */
export function buildDenylist(repos: string[], ids: number[] = []): Denylist {
  return {
    comment: 'Generated by scripts/gen-deploy-denylist.ts from infra/vps/files/lw-git/apps/*/app.conf (REPO=) plus fixed entries. Do not edit by hand.',
    fullNames: [...new Set([...repos, ...EXTRA_FULL_NAMES])].sort((a, b) => a.toLowerCase().localeCompare(b.toLowerCase())),
    names: [...BARE_NAMES],
    ids: [...new Set(ids)].sort((a, b) => a - b),
  };
}

function main(): void {
  const dir = process.env['LW_INFRA_DIR'] || resolve(ROOT, '..', 'infra');
  const repos = readAppConfRepos(dir);
  if (repos.length === 0) throw new Error(`LW_INFRA_DIR=${dir}: no REPO= line found in any app.conf`);
  const prev = existsSync(DENYLIST_PATH) ? (JSON.parse(readFileSync(DENYLIST_PATH, 'utf8')) as Partial<Denylist>) : {};
  writeFileSync(SNAPSHOT_PATH, `# REPO= sources of infra/vps/files/lw-git/apps/*/app.conf, written by scripts/gen-deploy-denylist.ts\n${repos.join('\n')}\n`);
  writeFileSync(DENYLIST_PATH, `${JSON.stringify(buildDenylist(repos, prev.ids ?? []), null, 2)}\n`);
  process.stdout.write(`${repos.length} deploy source(s): ${repos.join(', ')}\n`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) main();
